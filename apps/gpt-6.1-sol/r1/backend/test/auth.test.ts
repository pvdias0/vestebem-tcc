import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../src/app.js';
import { openDatabase } from '../src/database.js';

test('cadastro, isolamento, validação, logout e persistência real', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'vestebem-test-'));
  const path = join(directory, 'test.sqlite');
  let db = openDatabase(path);
  let server = createApp(db).listen(0, '127.0.0.1');
  await new Promise<void>(resolve => server.once('listening', resolve));
  let address = server.address();
  assert.ok(address && typeof address !== 'string');
  let base = `http://127.0.0.1:${address.port}`;
  const request = (route: string, body?: unknown, cookie = '', origin?: string) => fetch(`${base}/api/${route}`, { method: body === undefined ? 'GET' : 'POST', headers: { 'Content-Type': 'application/json', cookie, ...(origin ? { origin } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  const close = () => new Promise<void>((resolve, reject) => server.close(e => e ? reject(e) : resolve()));
  try {
    assert.equal((await request('me')).status, 401);
    assert.equal((await request('register', { name: 'A', email: 'x', password: 'a' })).status, 400);
    const alice = { name: 'Alice Silva', email: 'Alice@exemplo.com', password: 'senha-segura-123', role: 'admin' };
    assert.equal((await request('register', alice)).status, 201);
    assert.equal(db.prepare('SELECT role FROM users').get()?.role, 'customer');
    assert.equal((await request('register', { ...alice, email: 'alice@exemplo.com' })).status, 409);
    assert.equal((await request('login', { ...alice, password: 'errada' })).status, 401);
    assert.equal((await request('login', { email: 'ausente@exemplo.com', password: alice.password })).status, 401);
    assert.equal((await request('login', alice, '', 'http://malicioso.test')).status, 403);
    const login = await request('login', alice);
    assert.equal(login.status, 200);
    const cookie = login.headers.get('set-cookie')!.split(';')[0];
    assert.match(login.headers.get('set-cookie')!, /HttpOnly/);
    assert.match(login.headers.get('set-cookie')!, /SameSite=Lax/);
    assert.ok(!JSON.stringify(await login.json()).includes('password'));
    const me = await (await request('me', undefined, cookie)).json();
    assert.equal(me.user.name, alice.name);
    assert.equal(me.user.email, 'alice@exemplo.com');
    assert.equal((await request('register', { name: 'Bruno', email: 'bruno@exemplo.com', password: alice.password })).status, 201);
    const secondLogin = await request('login', { email: 'bruno@exemplo.com', password: alice.password });
    const secondCookie = secondLogin.headers.get('set-cookie')!.split(';')[0];
    assert.equal((await (await request('me', undefined, secondCookie)).json()).user.name, 'Bruno');
    assert.equal((await request('logout', {}, cookie)).status, 204);
    assert.equal((await request('me', undefined, cookie)).status, 401);
    assert.equal((await request('me', undefined, secondCookie)).status, 200);
    db.prepare('UPDATE sessions SET expires_at = 0').run();
    assert.equal((await request('me', undefined, secondCookie)).status, 401);
    const stored = db.prepare('SELECT password_hash FROM users LIMIT 1').get()!.password_hash;
    assert.notEqual(stored, alice.password);
    await close(); db.close();
    db = openDatabase(path);
    server = createApp(db).listen(0, '127.0.0.1');
    await new Promise<void>(resolve => server.once('listening', resolve));
    address = server.address();
    assert.ok(address && typeof address !== 'string');
    base = `http://127.0.0.1:${address.port}`;
    assert.equal((await request('login', alice)).status, 200);
    assert.equal(db.prepare('SELECT count(*) AS total FROM migrations').get()!.total, 5);
  } finally { await close(); db.close(); rmSync(directory, { recursive: true, force: true }); }
});
