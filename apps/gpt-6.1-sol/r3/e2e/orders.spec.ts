import { test, expect } from '@playwright/test';
import { once } from 'node:events';
import { resolve } from 'node:path';
import { openDatabase } from '../backend/src/db.js';
import { createApp } from '../backend/src/app.js';
import { seedDemo } from '../backend/src/seed.js';
import type { Server } from 'node:http';
let server: Server;
let db: ReturnType<typeof openDatabase>;
test.beforeAll(async () => {
 process.env.APP_ORIGIN = 'http://localhost:3101';
 db = openDatabase(resolve('test-results/browser.sqlite'));
 seedDemo(db);
 server = createApp(db).listen(3101, '127.0.0.1');
 await once(server, 'listening');
});
test.afterAll(async () => {
 if (server?.listening) { const closed = once(server, 'close'); server.close(); server.closeAllConnections(); await closed; }
 db?.close();
});
